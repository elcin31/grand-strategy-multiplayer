"""Derive immutable port sites from the existing public-domain map.
No geometry/territory/city changes; no runtime GIS dependency. Only exterior
coasts count: internal simplification holes/unrepresented territory are not seas.
"""
import hashlib,json
from pathlib import Path
from shapely.geometry import Polygon,MultiLineString
from shapely import make_valid,unary_union
root=Path(__file__).resolve().parents[1]
source=root/'src/world/data/geometry.json'
rows=json.loads(source.read_text())
geometries={r['id']:unary_union([make_valid(Polygon(rings[0],rings[1:])) for rings in r['polygons']]) for r in rows}
# Close rounding/simplification seams, without rewriting the displayed map.
land=unary_union(list(geometries.values())).buffer(.025).buffer(-.025)
parts=list(land.geoms) if hasattr(land,'geoms') else [land]
shore=MultiLineString([p.exterior.coords for p in parts])
# Buffer each small province boundary instead of one enormous world coastline.
# The latter creates a costly global overlay for no runtime/gameplay benefit.
ids=sorted(id for id,g in geometries.items() if g.boundary.buffer(.06).intersection(shore).length>max(.1,g.boundary.length*.005))
data={'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'method':'Existing map union; close0.025-unit seams; exterior coasts only (no internal holes); province boundary buffer0.06; coast intersection>max0.1,0.5% perimeter. Approximate scenario coastal sites, not a navigation survey.','provinceCount':len(rows),'waterAccessProvinceIds':ids}
target=root/'supabase/functions/_shared/waterAccess.ts'
target.write_text('// Generated by scripts/derive-water-access.py from existing Natural Earth public-domain map.\nexport const WATER_ACCESS = new Set<string>('+json.dumps(ids,separators=(',',':'))+');\nexport const WATER_ACCESS_SOURCE_SHA = '+json.dumps(data['sourceSha256'])+';\n')
(root/'WATER_ACCESS_REPORT.json').write_text(json.dumps(data,indent=2)+'\n')
print(json.dumps({'worldProvinces':len(rows),'waterAccessSites':len(ids),'sourceSha256':data['sourceSha256']}))
