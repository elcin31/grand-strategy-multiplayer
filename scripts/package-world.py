"""Package attributed prepared data for one shared gameplay factory and GPU geometry.
Province/city populations are normalized scenario estimates, not census counts.
"""
import argparse, hashlib, json, math
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--world-dir',type=Path,required=True);a=p.parse_args()
root=Path(__file__).resolve().parents[1]
load=lambda path:json.loads(path.read_text())
countries=load(root/'src/world/data/countries.json');provinces=load(a.world_dir/'provinces.json');cities=load(a.world_dir/'cities.json')
source=load(root/'src/world/data/source.json')
for name in ['countries','provinces','cities']:
 assert hashlib.sha256((a.world_dir/(name+'.json')).read_bytes()).hexdigest()==source['inputHashes'][name], 'Prepared data changed: '+name
# One geometry set outside campaign snapshots: no coordinates/polygons in server state.
geometry=[{'id':v['id'],'anchor':v['anchor'],'polygons':v['polygons']} for v in provinces]
city_by_id={c['id']:c for c in cities}
def area(v):
 total=0
 for rings in v['polygons']:
  for i,ring in enumerate(rings):
   value=abs(sum(x[0]*y[1]-y[0]*x[1] for x,y in zip(ring,ring[1:])))/2
   total += value if i==0 else -value
 return max(total,1e-8)
def allocate(total,weights):
 denominator=sum(weights); exact=[total*w/denominator for w in weights]; values=[math.floor(v) for v in exact]
 for i in sorted(range(len(values)),key=lambda i:(-(exact[i]-values[i]),i))[:total-sum(values)]:values[i]+=1
 return values
province_by_id={v['id']:v for v in provinces};rows=[];city_rows=[]
for country in countries:
 owned=[province_by_id[i] for i in country['provinceIds']]
 weights=[sum(city_by_id[i]['populationEstimate'] for i in v['cityIds'])+math.sqrt(area(v))*1000 for v in owned]
 populations=allocate(country['populationEstimate'],weights)
 for v,population in zip(owned,populations):
  seed=int(hashlib.sha256(v['id'].encode()).hexdigest()[:8],16);development=30+seed%41
  points=[pt for rings in v['polygons'] for ring in rings for pt in ring];xs=[pt[0] for pt in points];ys=[pt[1] for pt in points]
  rows.append({'id':v['id'],'name':v['name'],'countryId':v['countryId'],'neighbors':v['neighbors'],'cityIds':v['cityIds'],'population':population,'development':development,'income':max(1,round(population/300000*(.5+development/100))),'x':v['anchor'][0],'y':v['anchor'][1],'width':max(xs)-min(xs),'height':max(ys)-min(ys)})
  local_cities=[city_by_id[i] for i in v['cityIds']]
  estimated=sum(c['populationEstimate'] for c in local_cities)
  shares=allocate(min(population,estimated),[max(1,c['populationEstimate']) for c in local_cities]) if local_cities else []
  for c,value in zip(local_cities,shares):city_rows.append({'id':c['id'],'name':c['name'],'countryId':c['countryId'],'provinceId':c['provinceId'],'population':value,'development':development,'isCapital':c['isCapital'],'isRegionalCapital':c['isRegionalCapital']})
rows.sort(key=lambda v:v['id']);city_rows.sort(key=lambda v:v['id'])
header="""// Generated by scripts/package-world.py. Natural Earth public domain; original game estimates.
export interface CountryDefinition { id: string; name: string; shortName: string; color: string; adjective: string; flag: string; capitalCityId: string; provinceIds: string[]; populationEstimate: number; region: string; }
export interface ProvinceDefinition { id: string; name: string; countryId: string; neighbors: string[]; cityIds: string[]; population: number; development: number; income: number; x: number; y: number; width: number; height: number; }
export interface CityDefinition { id: string; name: string; countryId: string; provinceId: string; population: number; development: number; isCapital: boolean; isRegionalCapital: boolean; }
"""
minimal=[{key:c[key] for key in ['id','name','shortName','color','adjective','flag','capitalCityId','provinceIds','populationEstimate','region']} for c in countries]
compact=lambda data:json.dumps(data,ensure_ascii=False,separators=(',',':'))
world_data_dir=root/'supabase/functions/_shared/worldData'
world_data_dir.mkdir(parents=True,exist_ok=True)
imports=[]
exports=[]
for name,kind,data in [('countryDefinitions','CountryDefinition',minimal),('provinceDefinitions','ProvinceDefinition',rows),('cityDefinitions','CityDefinition',city_rows)]:
 batches=[]
 chunk_size=100 if kind!='CityDefinition' else 200
 for i in range(0,len(data),chunk_size):
  batch=name+'Batch'+str(i//chunk_size);batches.append(batch)
  filename=f'{name}-{i//chunk_size:02d}.ts'
  (world_data_dir/filename).write_text(f'import type {{ {kind} }} from "../worldDefinitions.ts";\nexport const data: {kind}[] = '+compact(data[i:i+chunk_size])+';\n')
  imports.append(f'import {{ data as {batch} }} from "./worldData/{filename}";')
 exports.append(f'export const {name}: readonly {kind}[] = ['+','.join('...'+b for b in batches)+'];')
(root/'supabase/functions/_shared/worldDefinitions.ts').write_text(header+'\n'.join(imports)+'\n'+'\n'.join(exports)+'\n')
(root/'src/world/data/geometry.json').write_text(compact(geometry)+'\n')
(root/'src/world/data/city-points.json').write_text(compact([{'id':c['id'],'point':c['point']} for c in cities])+'\n')
print(f'Packaged {len(countries)} countries / {len(rows)} provinces / {len(city_rows)} cities')
